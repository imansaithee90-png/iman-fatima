# Program 5: Conditional Statements

# If Statement
age = 18

if age >= 18:
    print("You are eligible to vote.")

# If-Else Statement
marks = 35

if marks >= 40:
    print("You passed.")
else:
    print("You failed.")

# If-Elif-Else Statement
number = 0

if number > 0:
    print("Positive number")
elif number < 0:
    print("Negative number")
else:
    print("Zero")